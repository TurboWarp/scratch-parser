/**
 * @fileoverview Compile ajv schemas into generated JS.
 */

const fs = require('fs');
const path = require('path');
const Ajv = require('ajv').default;
const standaloneCode = require('ajv/dist/standalone').default;
const ajvVersion = require('ajv/package.json').version;
const sb2Definitions = require('../lib/sb2_definitions.json');
const sb3Definitions = require('../lib/sb3_definitions.json');
const sb2Schema = require('../lib/sb2_schema.json');
const sb3Schema = require('../lib/sb3_schema.json');
const sprite2Schema = require('../lib/sprite2_schema.json');
const sprite3Schema = require('../lib/sprite3_schema.json');

const OUTPUT_DIRECTORY = path.join(__dirname, '..', 'lib', 'generated');

// Each file exports a validator for projects and for sprites. They are in the same file so that
// the code for the definitions they share is only generated once.
const FILES = {
    'sb2_validators.js': {
        project: sb2Schema,
        sprite: sprite2Schema
    },
    'sb3_validators.js': {
        project: sb3Schema,
        sprite: sprite3Schema
    }
};

/**
 * @param {object} [options] Additional ajv options
 * @returns {Ajv} ajv instance with all definitions and schemas added
 */
const createAjv = options => new Ajv({
    // Our schemas intentionally use open-ended tuples and union types
    strictTuples: false,
    strictTypes: false,
    allowUnionTypes: true,
    // NaN and Infinity are valid numbers. Projects can contain them, e.g. JSON.parse turns 1e400 into Infinity.
    strictNumbers: false,
    // This fixes a 1.5x slowdown in the generated validation.
    jsPropertySyntax: true,
    schemas: [sb2Definitions, sb3Definitions, sb2Schema, sb3Schema, sprite2Schema, sprite3Schema],
    ...options
});

/**
 * @returns {object} Map of file name in lib/generated/ to its contents.
 */
const generate = () => {
    const ajv = createAjv({
        code: {
            source: true,
            // Makes the generated code easier to read and diff
            lines: true
        }
    });

    const header = `// Generated by scripts/build-validators.js using ajv ${ajvVersion}. Do not edit.\n`;
    const files = {};
    for (const [fileName, schemas] of Object.entries(FILES)) {
        const exports = {};
        for (const [exportName, schema] of Object.entries(schemas)) {
            exports[exportName] = schema.$id;
        }
        files[fileName] = header + standaloneCode(ajv, exports);
    }
    return files;
};

module.exports = {
    OUTPUT_DIRECTORY,
    FILES,
    createAjv,
    generate
};

if (require.main === module) {
    fs.rmSync(OUTPUT_DIRECTORY, {recursive: true, force: true});
    fs.mkdirSync(OUTPUT_DIRECTORY, {recursive: true});
    for (const [fileName, contents] of Object.entries(generate())) {
        fs.writeFileSync(path.join(OUTPUT_DIRECTORY, fileName), contents);
        console.log(`Wrote lib/generated/${fileName}`);
    }
}
